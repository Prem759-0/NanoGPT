def get_active_policy() -> str:
    """Returns the immutable active ownership policy identifier."""
    return POLICY_STRICT_SOVEREIGN_RANDOM_INIT


def is_valid_policy(policy: str) -> bool:
    """
    Checks whether a given policy string is an authorized production ownership policy.
    Historical quarantined policies (e.g. TEACHER_STUDENT_RANDOM_INIT) return False.
    """
    return policy in VALID_PRODUCTION_POLICIES


def is_historical_policy(policy: str) -> bool:
    """Checks whether a given policy string is a recognized historical quarantined policy."""
    return policy in HISTORICAL_QUARANTINED_POLICIES


def validate_production_policy(policy: str) -> None:
    """
    Validates that a policy string is authorized for production development or training.
    Fails closed with SovereignPolicyViolationError if historical or unauthorized policy is provided.
    """
    if policy in HISTORICAL_QUARANTINED_POLICIES:
        raise SovereignPolicyViolationError(
            f"❌ SOVEREIGN POLICY VIOLATION: Policy '{policy}' is a QUARANTINED HISTORICAL POLICY. "
            f"Historical teacher policies are strictly forbidden from authorizing production model "
            f"development, training, evaluation, or dataset preparation. "
            f"Only '{POLICY_STRICT_SOVEREIGN_RANDOM_INIT}' is authorized."
        )
    if policy not in VALID_PRODUCTION_POLICIES:
        raise SovereignPolicyViolationError(
            f"❌ SOVEREIGN POLICY VIOLATION: Policy '{policy}' is UNKNOWN or UNAUTHORIZED. "
            f"Authorized production policies: {VALID_PRODUCTION_POLICIES}."
        )


def is_production_training_authorized() -> bool:
    """Checks whether production training execution is authorized."""
    return AUTHORIZED_BY_PREM and is_valid_policy(get_active_policy())


def assert_production_training_authorized(subsystem: Optional[str] = None) -> None:
    """
    Asserts both that the active policy is valid for production and that AUTHORIZED_BY_PREM is True.
    """
    validate_production_policy(get_active_policy())
    if not AUTHORIZED_BY_PREM:
        if subsystem:
            if subsystem.endswith("BLOCKED"):
                prefix = subsystem
            elif subsystem == "COLAB TRAINING RUNNER":
                prefix = "COLAB TRAINING RUNNER BLOCKED"
            else:
                prefix = f"{subsystem} TRAINING BLOCKED"
        else:
            prefix = "TRAINING EXECUTION BLOCKED"
        raise PermissionError(
            f"🔒 {prefix}: AUTHORIZED_BY_PREM is False. "
            f"Production training, checkpoint generation, and model weight modification require "
            f"explicit authorization from Prem Gaikwad (Chief ML Systems Architect, India 🇮🇳)."
        )


def validate_student_initialization(
    init_method: str,
    checkpoint_metadata: Optional[Dict[str, Any]] = None
) -> Tuple[bool, str]:
    """
    Validates that a student model was initialized legitimately from random weights.
    Strictly forbids initializing student weights from external foundation models.
    """
    if init_method not in VALID_STUDENT_INIT_METHODS:
        return False, (
            f"Invalid student initialization method '{init_method}'. "
            f"Must be one of {VALID_STUDENT_INIT_METHODS}. Initializing from pretrained checkpoints is strictly forbidden."
        )

    if checkpoint_metadata:
        base_weights = checkpoint_metadata.get("base_weights") or checkpoint_metadata.get("pretrained_source")
        if base_weights and base_weights not in ("none", "scratch", "random_gaussian"):
            return False, (
                f"Ownership violation: Checkpoint declares external base weights '{base_weights}'. "
                "Moon student models must be initialized from random Gaussian scratch weights."
            )

    return True, "Student initialization verified: purely random scratch weights."


def get_policy_summary(policy: Optional[str] = None) -> Dict[str, Any]:
    """
    Returns a comprehensive summary of policy rules and architectural definitions.
    Historical quarantined policies can be inspected for audit without activating them.
    """
    pol = policy or get_active_policy()
    is_prod = pol in VALID_PRODUCTION_POLICIES
    is_hist = pol in HISTORICAL_QUARANTINED_POLICIES
    rules = POLICY_RULES.get(pol, {})
    return {
        "policy": pol,
        "is_active": pol == get_active_policy(),
        "is_production_valid": is_prod,
        "is_quarantined_historical": is_hist,
        "can_authorize_training": is_prod and (pol == get_active_policy()),
        "rules": rules,
        "definitions": POLICY_DEFINITIONS
    }
