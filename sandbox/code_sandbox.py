"""
sandbox/code_sandbox.py
Sovereign Python Code Execution Sandbox for Moon AI.

Chief ML Systems Architect: Prem Gaikwad (India 🇮🇳)
Ownership Policy: STRICT_SOVEREIGN_SANDBOX_POLICY (100% Offline, Zero Cloud Dependencies)

Provides secure, isolated execution of Python code generated by Moon AI or submitted by users.
Features:
1. Static AST Security Analysis:
   - Blocks dangerous system calls (os.system, subprocess, eval, exec, compile, etc.)
   - Blocks network sockets and web clients (socket, requests, urllib, http, etc.)
   - Blocks file deletion / destructive host filesystem operations.
2. Isolated Execution Environment:
   - Executes inside an isolated temporary directory or designated sandbox directory.
   - Strips sensitive host environment variables.
   - Strictly enforces configurable timeout (default 5.0 seconds).
3. Artifact Capture:
   - Captures stdout and stderr.
   - Detects and collects generated artifacts (e.g. PNG/SVG plots, CSVs, TXT files).
   - Returns structured JSON with duration, exit code, and security status.
"""

import os
import sys
import time
import tempfile
import subprocess
import ast
import shutil
import glob
from typing import Dict, Any, List, Optional, Set

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SANDBOX_OUTPUT_DIR = os.path.join(PROJECT_ROOT, "data", "sandbox")


class SandboxSecurityError(Exception):
    """Raised when code violates sovereign sandbox security rules."""
    pass


class SovereignCodeSandbox:
    """
    Offline secure sandbox for executing user and agent Python code.
    """

    # Prohibited modules that could allow network communication, host breakout, or process spawning
    PROHIBITED_MODULES: Set[str] = {
        "socket", "urllib", "urllib3", "requests", "http", "httpx", "aiohttp",
        "subprocess", "shutil", "winreg", "ctypes", "pty", "multiprocessing",
        "signal", "posix", "nt", "pty", "ftplib", "smtplib", "telnetlib",
        "paramiko", "asyncio.subprocess"
    }

    # Prohibited function calls and attributes that could compromise host integrity
    PROHIBITED_CALLS: Set[str] = {
        "system", "popen", "spawn", "fork", "kill", "remove", "unlink",
        "rmdir", "rmtree", "eval", "exec", "compile", "__import__", "globals",
        "locals", "input"
    }

    # Prohibited attribute accesses
    PROHIBITED_ATTRS: Set[str] = {
        "__subclasses__", "__bases__", "__globals__", "__builtins__"
    }

    def __init__(
        self,
        python_executable: str = sys.executable,
        timeout_seconds: float = 7.0,
        sandbox_dir: Optional[str] = None
    ):
        self.python_executable = python_executable
        self.timeout_seconds = timeout_seconds
        self.sandbox_dir = sandbox_dir or SANDBOX_OUTPUT_DIR
        os.makedirs(self.sandbox_dir, exist_ok=True)

    def analyze_ast(self, code: str) -> None:
        """
        Parses and audits code AST for dangerous nodes.
        Raises SandboxSecurityError if security violation is detected.
        """
        try:
            tree = ast.parse(code)
        except SyntaxError:
            # Let syntax errors be caught naturally by the Python runtime
            return

        for node in ast.walk(tree):
            # 1. Audit explicit imports: import X, import X.Y
            if isinstance(node, ast.Import):
                for alias in node.names:
                    root_pkg = alias.name.split(".")[0].lower()
                    if root_pkg in self.PROHIBITED_MODULES:
                        raise SandboxSecurityError(
                            f"Security Violation: Import of module '{alias.name}' is prohibited in the sovereign sandbox."
                        )

            # 2. Audit from-imports: from X import Y
            elif isinstance(node, ast.ImportFrom):
                if node.module:
                    root_pkg = node.module.split(".")[0].lower()
                    if root_pkg in self.PROHIBITED_MODULES:
                        raise SandboxSecurityError(
                            f"Security Violation: Import from module '{node.module}' is prohibited in the sovereign sandbox."
                        )

            # 3. Audit direct function calls
            elif isinstance(node, ast.Call):
                func_name = None
                if isinstance(node.func, ast.Name):
                    func_name = node.func.id
                elif isinstance(node.func, ast.Attribute):
                    func_name = node.func.attr

                if func_name and func_name in self.PROHIBITED_CALLS:
                    raise SandboxSecurityError(
                        f"Security Violation: Invocation of '{func_name}()' is prohibited in the sovereign sandbox."
                    )

            # 4. Audit attribute access for introspection exploits
            elif isinstance(node, ast.Attribute):
                if node.attr in self.PROHIBITED_ATTRS:
                    raise SandboxSecurityError(
                        f"Security Violation: Access to attribute '{node.attr}' is prohibited in the sovereign sandbox."
                    )

    def execute(self, code: str, timeout_override: Optional[float] = None) -> Dict[str, Any]:
        """
        Executes Python code in an isolated temporary workspace.
        Captures stdout, stderr, execution duration, and generated files.
        """
        t0 = time.time()
        timeout = timeout_override or self.timeout_seconds

        # 1. Static AST Security Audit
        try:
            self.analyze_ast(code)
        except SandboxSecurityError as sse:
            return {
                "success": False,
                "output": "",
                "error": f"🔒 Sovereign Sandbox Security Block: {str(sse)}",
                "exit_code": -2,
                "duration_ms": round((time.time() - t0) * 1000, 2),
                "ast_security": "REJECTED",
                "artifacts": []
            }

        # 2. Create isolated run directory
        work_dir = tempfile.mkdtemp(prefix="moon_sandbox_", dir=self.sandbox_dir)
        script_path = os.path.join(work_dir, "run_script.py")

        try:
            with open(script_path, "w", encoding="utf-8") as f:
                f.write(code)

            # Sanitized environment: strip API keys, database connection strings, and tokens
            sanitized_env = {
                "SYSTEMROOT": os.environ.get("SYSTEMROOT", "C:\\Windows"),
                "SystemDrive": os.environ.get("SystemDrive", "C:"),
                "COMSPEC": os.environ.get("COMSPEC", "C:\\Windows\\system32\\cmd.exe"),
                "PATH": os.environ.get("PATH", ""),
                "PYTHONIOENCODING": "utf-8",
                "PYTHONUNBUFFERED": "1",
                "PYTHONDONTWRITEBYTECODE": "1",
                "MPLBACKEND": "Agg",  # Ensure matplotlib uses headless non-interactive backend
                "HOME": work_dir,
                "TMP": work_dir,
                "TEMP": work_dir
            }

            # 3. Subprocess execution (using -B to avoid writing bytecode files in ephemeral sandbox dir)
            process = subprocess.run(
                [self.python_executable, "-B", "run_script.py"],
                cwd=work_dir,
                capture_output=True,
                text=True,
                timeout=timeout,
                env=sanitized_env
            )

            duration_ms = round((time.time() - t0) * 1000, 2)
            stdout = process.stdout or ""
            stderr = process.stderr or ""
            success = (process.returncode == 0)

            # 4. Collect generated artifacts (plots, data files, images)
            artifacts = []
            for item in os.listdir(work_dir):
                if item == "run_script.py":
                    continue
                full_path = os.path.join(work_dir, item)
                if os.path.isfile(full_path):
                    # Copy to persistent sandbox dir with unique prefix
                    unique_name = f"artifact_{int(time.time()*1000)}_{item}"
                    dest_path = os.path.join(self.sandbox_dir, unique_name)
                    shutil.copy2(full_path, dest_path)
                    artifacts.append({
                        "filename": item,
                        "path": dest_path,
                        "size_bytes": os.path.getsize(dest_path)
                    })

            return {
                "success": success,
                "output": stdout,
                "error": stderr if not success else None,
                "exit_code": process.returncode,
                "duration_ms": duration_ms,
                "ast_security": "APPROVED",
                "artifacts": artifacts
            }

        except subprocess.TimeoutExpired:
            return {
                "success": False,
                "output": "",
                "error": f"⏱️ Execution Timeout: Code exceeded maximum allowed time limit of {timeout}s.",
                "exit_code": -1,
                "duration_ms": round((time.time() - t0) * 1000, 2),
                "ast_security": "APPROVED",
                "artifacts": []
            }
        except Exception as e:
            return {
                "success": False,
                "output": "",
                "error": f"Runtime Exception: {str(e)}",
                "exit_code": -3,
                "duration_ms": round((time.time() - t0) * 1000, 2),
                "ast_security": "APPROVED",
                "artifacts": []
            }
        finally:
            # Clean up temporary execution directory
            try:
                shutil.rmtree(work_dir, ignore_errors=True)
            except Exception:
                pass


# Global singleton instance
_default_sandbox = SovereignCodeSandbox()

def execute_code(code: str, timeout: Optional[float] = None) -> Dict[str, Any]:
    """Top-level helper to execute code in the sovereign sandbox."""
    return _default_sandbox.execute(code, timeout_override=timeout)

