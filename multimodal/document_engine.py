    def __init__(self, output_dir: Optional[str] = None):
        self.output_dir = output_dir or os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data", "documents"))
        os.makedirs(self.output_dir, exist_ok=True)

    # =========================================================================
    # 1. SOVEREIGN PDF GENERATION (PDF-1.4 Specification)
    # =========================================================================

    def generate_pdf(
        self,
        title: str,
        sections: List[Dict[str, Any]],
        author: str = "Prem Gaikwad (Moon AI Sovereign Core, India)",
        output_filename: Optional[str] = None
    ) -> str:
        """
        Generates a valid, readable PDF 1.4 document from structured sections.
        Each section can have:
          - 'heading': str
          - 'body': str
          - 'table': Optional[Dict[str, Any]] with 'headers' and 'rows'
        """
        filename = output_filename or f"moon_doc_{int(datetime.now().timestamp())}.pdf"
        if not filename.endswith(".pdf"):
            filename += ".pdf"
        out_path = os.path.join(self.output_dir, filename)

        # Build PDF stream commands
        stream_lines = []
        stream_lines.append("BT")
        stream_lines.append("/F2 20 Tf")
        stream_lines.append("50 750 Td")
        safe_title = title.replace("(", "\\(").replace(")", "\\)")
        stream_lines.append(f"({safe_title}) Tj")

        # Author / metadata
        stream_lines.append("/F1 10 Tf")
        stream_lines.append("0 -20 Td")
        safe_author = author.replace("(", "\\(").replace(")", "\\)")
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        stream_lines.append(f"(Generated by: {safe_author} | Date: {now_str}) Tj")

        # Line separator
        stream_lines.append("ET")
        stream_lines.append("0.2 w")
        stream_lines.append("50 715 m 550 715 l S")
        stream_lines.append("BT")

        current_y = 690
        stream_lines.append(f"50 {current_y} Td")

        for sec in sections:
            heading = sec.get("heading", "")
            body = sec.get("body", "")
            table = sec.get("table")

            if heading:
                stream_lines.append("/F2 13 Tf")
                stream_lines.append("0 -25 Td")
                safe_h = heading.replace("(", "\\(").replace(")", "\\)")
                stream_lines.append(f"({safe_h}) Tj")
                stream_lines.append("/F1 10 Tf")
                stream_lines.append("0 -15 Td")

            if body:
                # Wrap body paragraphs
                words = body.split()
                line = []
                line_len = 0
                for w in words:
                    if line_len + len(w) + 1 > 75:
                        p_line = " ".join(line).replace("(", "\\(").replace(")", "\\)")
                        stream_lines.append(f"({p_line}) Tj")
                        stream_lines.append("0 -13 Td")
                        line = [w]
                        line_len = len(w)
                    else:
                        line.append(w)
                        line_len += len(w) + 1
                if line:
                    p_line = " ".join(line).replace("(", "\\(").replace(")", "\\)")
                    stream_lines.append(f"({p_line}) Tj")
                    stream_lines.append("0 -15 Td")

            if table and isinstance(table, dict):
                headers = table.get("headers", [])
                rows = table.get("rows", [])
                if headers:
                    stream_lines.append("/F2 10 Tf")
                    header_str = " | ".join(str(h) for h in headers).replace("(", "\\(").replace(")", "\\)")
                    stream_lines.append(f"([TABLE] {header_str}) Tj")
                    stream_lines.append("0 -12 Td")
                    stream_lines.append("/F1 9 Tf")
                for r in rows[:15]:
                    row_str = " | ".join(str(cell) for cell in r).replace("(", "\\(").replace(")", "\\)")
                    stream_lines.append(f"({row_str}) Tj")
                    stream_lines.append("0 -12 Td")
                stream_lines.append("0 -10 Td")

        stream_lines.append("ET")
        content_stream = "\n".join(stream_lines).encode("latin1", errors="replace")

        # Assemble PDF Object Tree
        objects = []
        # 1: Catalog
        objects.append(b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n")
        # 2: Pages
        objects.append(b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n")
        # 3: Page
        objects.append(
            b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
            b"/Contents 4 0 R /Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>\nendobj\n"
        )
        # 4: Content Stream
        stream_header = f"4 0 obj\n<< /Length {len(content_stream)} >>\nstream\n".encode("ascii")
        objects.append(stream_header + content_stream + b"\nendstream\nendobj\n")
        # 5: Font F1 (Helvetica)
        objects.append(b"5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n")
        # 6: Font F2 (Helvetica-Bold)
        objects.append(b"6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>\nendobj\n")

        with open(out_path, "wb") as f:
            f.write(b"%PDF-1.4\n")
            offsets = []
            for obj in objects:
                offsets.append(f.tell())
                f.write(obj)

            xref_pos = f.tell()
            f.write(b"xref\n")
            f.write(f"0 {len(objects) + 1}\n".encode("ascii"))
            f.write(b"0000000000 65535 f \n")
            for off in offsets:
                f.write(f"{off:010d} 00000 n \n".encode("ascii"))

            f.write(b"trailer\n")
            f.write(f"<< /Size {len(objects) + 1} /Root 1 0 R >>\n".encode("ascii"))
            f.write(b"startxref\n")
            f.write(f"{xref_pos}\n".encode("ascii"))
            f.write(b"%%EOF\n")

        return out_path

    # =========================================================================
    # 2. SOVEREIGN DOCX GENERATION (OpenXML Specification)
    # =========================================================================

    def generate_docx(
        self,
        title: str,
        sections: List[Dict[str, Any]],
        author: str = "Prem Gaikwad (Moon AI Sovereign Core, India)",
        output_filename: Optional[str] = None
    ) -> str:
        """
        Generates a valid Microsoft Word (.docx) document as an OpenXML ZIP container.
        """
        filename = output_filename or f"moon_doc_{int(datetime.now().timestamp())}.docx"
        if not filename.endswith(".docx"):
            filename += ".docx"
        out_path = os.path.join(self.output_dir, filename)

        # Build document.xml
        p_elements = []
        # Title
        p_elements.append(
            f'<w:p><w:pPr><w:pStyle w:val="Title"/><w:jc w:val="center"/></w:pPr>'
            f'<w:r><w:rPr><w:b/><w:sz w:val="48"/><w:color w:val="0F172A"/></w:rPr>'
            f'<w:t>{self._xml_escape(title)}</w:t></w:r></w:p>'
        )
        # Subtitle / author
        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        p_elements.append(
            f'<w:p><w:pPr><w:jc w:val="center"/></w:pPr>'
            f'<w:r><w:rPr><w:i/><w:sz w:val="20"/><w:color w:val="64748B"/></w:rPr>'
            f'<w:t>Author: {self._xml_escape(author)} | {now_str}</w:t></w:r></w:p>'
        )

        for sec in sections:
            heading = sec.get("heading", "")
            body = sec.get("body", "")
            table = sec.get("table")

            if heading:
                p_elements.append(
                    f'<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr>'
                    f'<w:r><w:rPr><w:b/><w:sz w:val="32"/><w:color w:val="1E293B"/></w:rPr>'
                    f'<w:t>{self._xml_escape(heading)}</w:t></w:r></w:p>'
                )

            if body:
                p_elements.append(
                    f'<w:p><w:r><w:rPr><w:sz w:val="22"/></w:rPr>'
                    f'<w:t>{self._xml_escape(body)}</w:t></w:r></w:p>'
                )

            if table and isinstance(table, dict):
                headers = table.get("headers", [])
                rows = table.get("rows", [])
                tbl_xml = ['<w:tbl><w:tblPr><w:tblBorders>'
                           '<w:top w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                           '<w:left w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                           '<w:bottom w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                           '<w:right w:val="single" w:sz="4" w:space="0" w:color="CBD5E1"/>'
                           '<w:insideH w:val="single" w:sz="4" w:space="0" w:color="E2E8F0"/>'
                           '<w:insideV w:val="single" w:sz="4" w:space="0" w:color="E2E8F0"/>'
                           '</w:tblBorders></w:tblPr>']
                if headers:
                    tbl_xml.append('<w:tr>')
                    for h in headers:
                        tbl_xml.append(
                            f'<w:tc><w:tcPr><w:shd w:val="clear" w:color="auto" w:fill="F1F5F9"/></w:tcPr>'
                            f'<w:p><w:r><w:rPr><w:b/><w:sz w:val="20"/></w:rPr>'
                            f'<w:t>{self._xml_escape(str(h))}</w:t></w:r></w:p></w:tc>'
                        )
                    tbl_xml.append('</w:tr>')

                for r in rows:
                    tbl_xml.append('<w:tr>')
                    for cell in r:
                        tbl_xml.append(
                            f'<w:tc><w:p><w:r><w:rPr><w:sz w:val="20"/></w:rPr>'
                            f'<w:t>{self._xml_escape(str(cell))}</w:t></w:r></w:p></w:tc>'
                        )
                    tbl_xml.append('</w:tr>')
                tbl_xml.append('</w:tbl>')
                p_elements.append("".join(tbl_xml))

        doc_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
            '<w:body>' + "".join(p_elements) + '<w:sectPr/></w:body></w:document>'
        )

        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
            '</Types>'
        )

        root_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>'
            '</Relationships>'
        )

        with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", content_types)
            zf.writestr("_rels/.rels", root_rels)
            zf.writestr("word/document.xml", doc_xml)

        return out_path

    # =========================================================================
    # 3. SOVEREIGN XLSX GENERATION (OpenXML SpreadsheetML)
    # =========================================================================

    def generate_xlsx(
        self,
        sheet_name: str,
        headers: List[str],
        rows: List[List[Any]],
        output_filename: Optional[str] = None
    ) -> str:
        """
        Generates a valid Microsoft Excel (.xlsx) spreadsheet as an OpenXML ZIP container.
        """
        filename = output_filename or f"moon_sheet_{int(datetime.now().timestamp())}.xlsx"
        if not filename.endswith(".xlsx"):
            filename += ".xlsx"
        out_path = os.path.join(self.output_dir, filename)

        def col_name(n: int) -> str:
            res = ""
            while n >= 0:
                res = chr(n % 26 + 65) + res
                n = n // 26 - 1
            return res

        sheet_rows = []
        # Header row (Row 1)
        row1_cells = []
        for c_idx, h in enumerate(headers):
            c_ref = f"{col_name(c_idx)}1"
            safe_val = self._xml_escape(str(h))
            row1_cells.append(f'<c r="{c_ref}" t="inlineStr"><is><t>{safe_val}</t></is></c>')
        sheet_rows.append(f'<row r="1">{"".join(row1_cells)}</row>')

        # Data rows (Row 2 .. N+1)
        for r_idx, row in enumerate(rows, start=2):
            cells = []
            for c_idx, val in enumerate(row):
                c_ref = f"{col_name(c_idx)}{r_idx}"
                if isinstance(val, (int, float)) and not isinstance(val, bool):
                    cells.append(f'<c r="{c_ref}"><v>{val}</v></c>')
                else:
                    safe_val = self._xml_escape(str(val))
                    cells.append(f'<c r="{c_ref}" t="inlineStr"><is><t>{safe_val}</t></is></c>')
            sheet_rows.append(f'<row r="{r_idx}">{"".join(cells)}</row>')

        sheet_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">'
            '<sheetData>' + "".join(sheet_rows) + '</sheetData></worksheet>'
        )

        workbook_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
            'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
            f'<sheets><sheet name="{self._xml_escape(sheet_name)}" sheetId="1" r:id="rId1"/></sheets>'
            '</workbook>'
        )

        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
            '<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
            '</Types>'
        )

        root_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
            '</Relationships>'
        )

        workbook_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>'
            '</Relationships>'
        )

        with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", content_types)
            zf.writestr("_rels/.rels", root_rels)
            zf.writestr("xl/workbook.xml", workbook_xml)
            zf.writestr("xl/_rels/workbook.xml.rels", workbook_rels)
            zf.writestr("xl/worksheets/sheet1.xml", sheet_xml)

        return out_path

    # =========================================================================
    # 4. SOVEREIGN PPTX GENERATION (OpenXML PresentationML)
    # =========================================================================

    def generate_pptx(
        self,
        title: str,
        subtitle: str,
        slides: List[Dict[str, Any]],
        output_filename: Optional[str] = None
    ) -> str:
        """
        Generates a valid Microsoft PowerPoint (.pptx) presentation as an OpenXML ZIP container.
        """
        filename = output_filename or f"moon_presentation_{int(datetime.now().timestamp())}.pptx"
        if not filename.endswith(".pptx"):
            filename += ".pptx"
        out_path = os.path.join(self.output_dir, filename)

        # Basic Presentation structure
        slide_parts = []
        # Title slide
        title_slide = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<p:sld xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" '
            'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">'
            '<p:cSld><p:spTree><p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>'
            '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>'
            f'<p:sp><p:nvSpPr><p:cNvPr id="2" name="Title"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr/></p:nvSpPr>'
            '<p:spPr><a:xfrm><a:off x="685800" y="1828800"/><a:ext cx="7772400" cy="1470025"/></a:xfrm></p:spPr>'
            f'<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="en-US" b="1" sz="4400"/><a:t>{self._xml_escape(title)}</a:t></a:r></a:p></p:txBody></p:sp>'
            f'<p:sp><p:nvSpPr><p:cNvPr id="3" name="Subtitle"/><p:cNvSpPr><a:spLocks noGrp="1"/></p:cNvSpPr><p:nvPr/></p:nvSpPr>'
            '<p:spPr><a:xfrm><a:off x="685800" y="3429000"/><a:ext cx="7772400" cy="1200000"/></a:xfrm></p:spPr>'
            f'<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="en-US" sz="2400"/><a:t>{self._xml_escape(subtitle)}</a:t></a:r></a:p></p:txBody></p:sp>'
            '</p:spTree></p:cSld></p:sld>'
        )
        slide_parts.append(title_slide)

        # Content slides
        for idx, sl in enumerate(slides, start=2):
            s_title = sl.get("title", f"Slide {idx}")
            s_bullets = sl.get("bullets", [])
            bullets_xml = []
            for b in s_bullets:
                bullets_xml.append(f'<a:p><a:pPr lvl="0"/><a:r><a:rPr lang="en-US" sz="2000"/><a:t>• {self._xml_escape(str(b))}</a:t></a:r></a:p>')

            s_xml = (
                '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
                '<p:sld xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" '
                'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">'
                '<p:cSld><p:spTree><p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>'
                '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>'
                f'<p:sp><p:nvSpPr><p:cNvPr id="2" name="Title"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>'
                '<p:spPr><a:xfrm><a:off x="685800" y="609600"/><a:ext cx="7772400" cy="800000"/></a:xfrm></p:spPr>'
                f'<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="en-US" b="1" sz="3600"/><a:t>{self._xml_escape(s_title)}</a:t></a:r></a:p></p:txBody></p:sp>'
                f'<p:sp><p:nvSpPr><p:cNvPr id="3" name="Content"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>'
                '<p:spPr><a:xfrm><a:off x="685800" y="1600000"/><a:ext cx="7772400" cy="4500000"/></a:xfrm></p:spPr>'
                f'<p:txBody><a:bodyPr/><a:lstStyle/>{"".join(bullets_xml)}</p:txBody></p:sp>'
                '</p:spTree></p:cSld></p:sld>'
            )
            slide_parts.append(s_xml)

        # Presentation XML
        sld_id_list = []
        for idx in range(1, len(slide_parts) + 1):
            sld_id_list.append(f'<p:sldId id="{255 + idx}" r:id="rId{idx}"/>')

        pres_xml = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<p:presentation xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" '
            'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
            f'<p:sldIdLst>{"".join(sld_id_list)}</p:sldIdLst>'
            '<p:sldSz cx="9144000" cy="6858000"/><p:notesSz cx="6858000" cy="9144000"/>'
            '</p:presentation>'
        )

        content_types_entries = [
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>',
            '<Default Extension="xml" ContentType="application/xml"/>',
            '<Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>'
        ]
        pres_rels_entries = []
        for idx in range(1, len(slide_parts) + 1):
            content_types_entries.append(
                f'<Override PartName="/ppt/slides/slide{idx}.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>'
            )
            pres_rels_entries.append(
                f'<Relationship Id="rId{idx}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide{idx}.xml"/>'
            )

        content_types = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">' + "".join(content_types_entries) + '</Types>'
        )
        root_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/>'
            '</Relationships>'
        )
        pres_rels = (
            '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">' + "".join(pres_rels_entries) + '</Relationships>'
        )

        with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("[Content_Types].xml", content_types)
            zf.writestr("_rels/.rels", root_rels)
            zf.writestr("ppt/presentation.xml", pres_xml)
            zf.writestr("ppt/_rels/presentation.xml.rels", pres_rels)
            for idx, s_xml in enumerate(slide_parts, start=1):
                zf.writestr(f"ppt/slides/slide{idx}.xml", s_xml)

        return out_path

    # =========================================================================
    # 5. SOVEREIGN DOCUMENT PARSING (PDF, DOCX, XLSX, CSV, JSON, TXT, MD)
    # =========================================================================

    def parse_document(self, filepath: str) -> Dict[str, Any]:
        """
        Parses text and tabular data from local files without external cloud APIs.
        Supports: .pdf, .docx, .xlsx, .csv, .json, .md, .txt, .py
        """
        if not os.path.isfile(filepath):
            raise FileNotFoundError(f"File not found: {filepath}")

        ext = os.path.splitext(filepath)[1].lower()
        size_bytes = os.path.getsize(filepath)

        result: Dict[str, Any] = {
            "filename": os.path.basename(filepath),
            "extension": ext,
            "size_bytes": size_bytes,
            "text": "",
            "tables": [],
            "metadata": {}
        }

        # CSV / TSV
        if ext in (".csv", ".tsv"):
            delimiter = "\t" if ext == ".tsv" else ","
            rows = []
            with open(filepath, "r", encoding="utf-8", errors="replace") as f:
                reader = csv.reader(f, delimiter=delimiter)
                for r in reader:
                    rows.append(r)
            result["tables"].append({"headers": rows[0] if rows else [], "rows": rows[1:] if len(rows) > 1 else []})
            result["text"] = "\n".join([", ".join(r) for r in rows[:100]])
            return result

        # JSON
        if ext == ".json":
            with open(filepath, "r", encoding="utf-8", errors="replace") as f:
                data = json.load(f)
            result["metadata"] = {"type": type(data).__name__, "keys": list(data.keys()) if isinstance(data, dict) else len(data)}
            result["text"] = json.dumps(data, indent=2, ensure_ascii=False)[:5000]
            return result

        # TXT / MD / PY
        if ext in (".txt", ".md", ".py", ".html", ".yaml", ".yml"):
            with open(filepath, "r", encoding="utf-8", errors="replace") as f:
                content = f.read()
            result["text"] = content
            return result

        # DOCX (OpenXML ZIP)
        if ext == ".docx":
            try:
                with zipfile.ZipFile(filepath, "r") as zf:
                    if "word/document.xml" in zf.namelist():
                        xml_content = zf.read("word/document.xml")
                        root = ET.fromstring(xml_content)
                        # Extract all text inside <w:t> tags
                        texts = [elem.text for elem in root.iter() if elem.tag.endswith("}t") and elem.text]
                        result["text"] = " ".join(texts)
            except Exception as e:
                result["metadata"]["error"] = f"DOCX parse warning: {str(e)}"
            return result

        # XLSX (OpenXML ZIP)
        if ext == ".xlsx":
            try:
                with zipfile.ZipFile(filepath, "r") as zf:
                    # Parse shared strings if present
                    shared_strings = []
                    if "xl/sharedStrings.xml" in zf.namelist():
                        s_root = ET.fromstring(zf.read("xl/sharedStrings.xml"))
                        shared_strings = [elem.text or "" for elem in s_root.iter() if elem.tag.endswith("}t")]

                    # Parse sheet1.xml
                    if "xl/worksheets/sheet1.xml" in zf.namelist():
                        w_root = ET.fromstring(zf.read("xl/worksheets/sheet1.xml"))
                        rows = []
                        for row_el in w_root.iter():
                            if row_el.tag.endswith("}row"):
                                current_row = []
                                for c_el in row_el:
                                    t_attr = c_el.get("t")
                                    # Check inline string or v element
                                    v_el = c_el.find("{http://schemas.openxmlformats.org/spreadsheetml/2006/main}v")
                                    if v_el is not None and v_el.text:
                                        val = v_el.text
                                        if t_attr == "s" and shared_strings:
                                            try:
                                                val = shared_strings[int(val)]
                                            except (IndexError, ValueError):
                                                pass
                                        current_row.append(val)
                                    else:
                                        t_el = c_el.find(".//{http://schemas.openxmlformats.org/spreadsheetml/2006/main}t")
                                        if t_el is not None and t_el.text:
                                            current_row.append(t_el.text)
                                if current_row:
                                    rows.append(current_row)

                        if rows:
                            result["tables"].append({"headers": rows[0], "rows": rows[1:]})
                            result["text"] = "\n".join(["\t".join(r) for r in rows[:50]])
            except Exception as e:
                result["metadata"]["error"] = f"XLSX parse warning: {str(e)}"
            return result

        # PDF (Pure regex/stream text extractor)
        if ext == ".pdf":
            try:
                with open(filepath, "rb") as f:
                    pdf_bytes = f.read()

                # Extract text within Tj / TJ text rendering operators
                text_chunks = []
                tj_matches = re.findall(rb"\((.*?)\)\s*Tj", pdf_bytes)
                for m in tj_matches:
                    try:
                        text_chunks.append(m.decode("latin1", errors="replace"))
                    except Exception:
                        pass

                result["text"] = " ".join(text_chunks)
                result["metadata"]["extracted_chunks"] = len(text_chunks)
            except Exception as e:
                result["metadata"]["error"] = f"PDF parse warning: {str(e)}"
            return result

        # Fallback binary / unhandled
        result["text"] = f"[Binary file: {ext}, size={size_bytes} bytes]"
        return result

    def _xml_escape(self, s: str) -> str:
        """Escapes XML reserved characters."""
        return (
            s.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace('"', "&quot;")
            .replace("'", "&apos;")
        )

